CREATE TABLE produk (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR NOT NULL,
    harga_per_kg NUMERIC NOT NULL,
    stok_kg NUMERIC NOT NULL DEFAULT 0,
    kategori VARCHAR NOT NULL,
    tanggal_masuk DATE NOT NULL DEFAULT CURRENT_DATE,
    masa_simpan_hari INT NOT NULL DEFAULT 7
);

CREATE TABLE transaksi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_telegram_id VARCHAR NOT NULL,
    total_harga NUMERIC NOT NULL DEFAULT 0,
    status VARCHAR NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE item_transaksi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaksi_id BIGINT REFERENCES transaksi(id) ON DELETE CASCADE,
    produk_id BIGINT REFERENCES produk(id) ON DELETE RESTRICT,
    jumlah_kg NUMERIC NOT NULL
);
